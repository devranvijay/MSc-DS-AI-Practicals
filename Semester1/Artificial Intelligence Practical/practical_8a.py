# ===== 8a. Associative Law =====
# Associative Law
A = 10
B = 5
C = 2
# Addition
left_add = (A + B) + C
right_add = A + (B + C)
# Multiplication
left_mul = (A * B) * C
right_mul = A * (B * C)
print("Associative Law of Addition:")
print("(A+B)+C =", left_add)
print("A+(B+C) =", right_add)
print("\nAssociative Law of Multiplication:")
print("(A*B)*C =", left_mul)
print("A*(B*C) =", right_mul)
print("\nBoth laws are verified.")
