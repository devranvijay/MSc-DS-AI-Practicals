# ===== 8b. Distributive Law =====
# Distributive Law
A = 10
B = 5
C = 2
# Distributive Law of Addition
left_add = A * (B + C)
right_add = (A * B) + (A * C)
# Distributive Law of Subtraction
left_sub = A * (B - C)
right_sub = (A * B) - (A * C)
print("Distributive Law of Addition:")
print("A*(B+C) =", left_add)
print("(A*B)+(A*C) =", right_add)
print("\nDistributive Law of Subtraction:")
print("A*(B-C) =", left_sub)
print("(A*B)-(A*C) =", right_sub)
print("\nBoth laws are verified.")
